//! `vibe99ctl skill` — install the agent-facing skill that teaches coding
//! agents to drive Vibe99.
//!
//! The skill is a `SKILL.md` file in the shape Claude Code, Codex and
//! Antigravity read: YAML frontmatter with the name and a trigger description,
//! then instructions. Its method catalogue is **generated from
//! [`crate::cli_registry::METHODS`]** — the same table `vibe99ctl describe`
//! renders — so the skill cannot fall behind the CLI: adding a method updates
//! both, and a test ([`tests::skill_documents_every_registered_method`]) fails
//! if a method ever goes unmentioned.
//!
//! Like `enhance`, this writes into directories Vibe99 does not own, so the
//! rules are the same:
//!
//! * A `SKILL.md` without the [`GENERATED_MARKER`] is the user's own skill.
//!   Install refuses to overwrite it and uninstall refuses to delete it;
//!   `--force` is the explicit override.
//! * Re-running install on a current file changes nothing and writes nothing.
//! * Uninstall removes the file (and its now-empty directory) only when it is
//!   ours, and leaves every other skill in place.
//! * Nothing prompts when stdin is not a terminal — the Windows installer runs
//!   `install-cli` with no console attached, and a prompt there would hang it.
//!   In that case the caller's non-interactive default applies.

use crate::cli_registry::{self, MethodSpec, ParamSpec};
use crate::enhance::write_atomic;
use clap::Subcommand;
use serde_json::{json, Value};
use std::fs;
use std::io::{self, IsTerminal, Write};
use std::path::{Path, PathBuf};

/// Directory (and frontmatter `name`) of the skill.
pub const SKILL_NAME: &str = "vibe99ctl";

/// Every generated `SKILL.md` starts with this after its frontmatter. It is
/// how install and uninstall tell our file from a hand-written one.
pub const GENERATED_MARKER: &str = "<!-- generated by vibe99ctl";

/// One agent environment the skill can be installed into.
pub struct SkillTarget {
    /// Stable id used by `--skill` and `skill install <id>`.
    pub id: &'static str,
    /// Human name.
    pub name: &'static str,
    /// Skill directories, relative to the home directory. A target can list
    /// more than one: Antigravity's CLI and its app/IDE read different folders,
    /// and the skill has to exist in the one the user's agent actually reads.
    pub dirs: &'static [&'static [&'static str]],
    /// Home-relative directories whose presence means the agent is installed.
    pub detect: &'static [&'static [&'static str]],
}

pub const CLAUDE_CODE: SkillTarget = SkillTarget {
    id: "claude-code",
    name: "Claude Code",
    dirs: &[&[".claude", "skills"]],
    detect: &[&[".claude"]],
};

pub const CODEX: SkillTarget = SkillTarget {
    id: "codex",
    name: "Codex",
    dirs: &[&[".codex", "skills"]],
    detect: &[&[".codex"]],
};

/// Antigravity keeps one skills folder per surface: the agent CLI reads
/// `~/.gemini/antigravity-cli/skills`, the 2.0 app and IDE read
/// `~/.gemini/config/skills`. Installing both is what makes the skill visible
/// whichever one the user drives.
pub const ANTIGRAVITY: SkillTarget = SkillTarget {
    id: "antigravity",
    name: "Antigravity",
    dirs: &[
        &[".gemini", "antigravity-cli", "skills"],
        &[".gemini", "config", "skills"],
    ],
    detect: &[&[".gemini", "antigravity-cli"], &[".gemini", "config"]],
};

/// Every supported agent environment.
pub static TARGETS: &[SkillTarget] = &[CLAUDE_CODE, CODEX, ANTIGRAVITY];

impl SkillTarget {
    /// Skill file paths this target reads, for a given home directory.
    pub fn files(&self, home: &Path) -> Vec<PathBuf> {
        self.dirs
            .iter()
            .map(|dir| home_dir_path(home, dir).join(SKILL_NAME).join("SKILL.md"))
            .collect()
    }

    /// Whether the agent looks installed on this machine.
    pub fn is_detected(&self, home: &Path) -> bool {
        self.detect
            .iter()
            .any(|parts| home_dir_path(home, parts).exists())
    }

    /// The directories as `~/…` strings, for prompts and JSON output.
    pub fn display_dirs(&self) -> String {
        self.dirs
            .iter()
            .map(|dir| format!("~/{}", dir.join("/")))
            .collect::<Vec<_>>()
            .join(", ")
    }
}

/// Resolve a home-relative path.
fn home_dir_path(home: &Path, parts: &[&str]) -> PathBuf {
    parts.iter().fold(home.to_path_buf(), |path, part| path.join(part))
}

/// Look up a target by id.
pub fn find(id: &str) -> Result<&'static SkillTarget, String> {
    TARGETS.iter().find(|target| target.id == id).ok_or_else(|| {
        format!(
            "unknown skill target \"{id}\"; supported: {}",
            TARGETS
                .iter()
                .map(|target| target.id)
                .collect::<Vec<_>>()
                .join(", ")
        )
    })
}

