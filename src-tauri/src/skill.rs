/// The `--skill` spec accepted by `install-cli` and `enhance install`.
#[derive(Debug, PartialEq, Eq)]
pub enum SkillChoice {
    /// Ask on the terminal; do nothing when there is no terminal.
    Ask,
    /// Install nothing.
    Skip,
    /// Every target, detected or not.
    All,
    /// The named targets.
    Only(Vec<String>),
}

/// Parse `ask`, `none`, `all`, or a comma-separated list of target ids.
pub fn parse_choice(spec: &str) -> Result<SkillChoice, String> {
    match spec.trim() {
        "" | "ask" => Ok(SkillChoice::Ask),
        "none" => Ok(SkillChoice::Skip),
        "all" => Ok(SkillChoice::All),
        other => {
            let ids: Vec<String> = other
                .split(',')
                .map(str::trim)
                .filter(|id| !id.is_empty())
                .map(str::to_string)
                .collect();
            if ids.is_empty() {
                return Err(format!(
                    "invalid --skill value \"{other}\"; use ask, none, all, or target ids"
                ));
            }
            // Reject unknown ids now rather than half-way through an install.
            for id in &ids {
                find(id)?;
            }
            Ok(SkillChoice::Only(ids))
        }
    }
}

fn resolve_choice(choice: &SkillChoice) -> Result<Vec<&'static SkillTarget>, String> {
    match choice {
        SkillChoice::Skip => Ok(Vec::new()),
        SkillChoice::All => Ok(TARGETS.iter().collect()),
        SkillChoice::Only(ids) => ids.iter().map(|id| find(id)).collect(),
        SkillChoice::Ask => Ok(Vec::new()),
    }
}

/// Ask a yes/no question on stderr, so stdout stays machine-readable.
///
/// Returns `None` when stdin is not a terminal: the Windows installer and CI
/// run this with nobody to answer, and waiting there would hang the install.
/// An unreadable or unexpected answer is treated as "no".
pub fn ask_yes_no(question: &str, default: bool) -> Option<bool> {
    if !io::stdin().is_terminal() {
        return None;
    }
    let hint = if default { "[Y/n]" } else { "[y/N]" };
    eprint!("{question} {hint} ");
    let _ = io::stderr().flush();

    let mut answer = String::new();
    match io::stdin().read_line(&mut answer) {
        Ok(0) | Err(_) => None,
        Ok(_) => Some(match answer.trim().to_ascii_lowercase().as_str() {
            "" => default,
            "y" | "yes" => true,
            _ => false,
        }),
    }
}

/// Install the skill as part of `vibe99ctl install-cli`.
///
/// `Ask` offers each agent detected on this machine, defaulting to yes; with
/// no terminal it prints the command to run later instead of blocking.
pub fn offer_install(choice: &SkillChoice) -> Result<Option<Value>, String> {
    if matches!(choice, SkillChoice::Skip) {
        return Ok(None);
    }
    let home = cli_registry::home_dir()?;

    let targets = if matches!(choice, SkillChoice::Ask) {
        if !io::stdin().is_terminal() {
            eprintln!(
                "The agent skill teaches Claude Code, Codex and Antigravity to drive vibe99ctl.\n\
                 Install it later with: vibe99ctl skill install"
            );
            return Ok(None);
        }
        let detected: Vec<&'static SkillTarget> = TARGETS
            .iter()
            .filter(|target| target.is_detected(&home))
            .collect();
        if detected.is_empty() {
            eprintln!(
                "No coding-agent environment found (looked for ~/.claude, ~/.codex, ~/.gemini).\n\
                 Run `vibe99ctl skill install --all` to install the skill anyway."
            );
            return Ok(None);
        }
        let mut chosen = Vec::new();
        for target in detected {
            match ask_yes_no(
                &format!(
                    "Install the Vibe99 skill for {} ({})?",
                    target.name,
                    target.display_dirs()
                ),
                true,
            ) {
                Some(true) => chosen.push(target),
                Some(false) => {}
                // EOF mid-prompt: keep what was accepted, ask nothing more.
                None => break,
            }
        }
        chosen
    } else {
        resolve_choice(choice)?
    };

    if targets.is_empty() {
        return Ok(None);
    }
    install_report(&targets, &home, false, false).map(Some)
}

/// Install the skill as part of `enhance install <agent>`, which already names
/// the agent: `Ask` prompts for that one target only.
pub fn offer_for_agent(agent_id: &str, choice: &SkillChoice) -> Result<Option<Value>, String> {
    let Some(target) = TARGETS.iter().find(|target| target.id == agent_id) else {
        return Ok(None);
    };
    let home = cli_registry::home_dir()?;

    let targets = if matches!(choice, SkillChoice::Ask) {
        if !io::stdin().is_terminal() {
            eprintln!(
                "To teach {} to drive Vibe99, run: vibe99ctl skill install {}",
                target.name, target.id
            );
            return Ok(None);
        }
        if ask_yes_no(
            &format!(
                "Also install the Vibe99 skill for {} ({})?",
                target.name,
                target.display_dirs()
            ),
            true,
        ) != Some(true)
        {
            return Ok(None);
        }
        vec![target]
    } else {
        resolve_choice(choice)?
    };

    if targets.is_empty() {
        return Ok(None);
    }
    install_report(&targets, &home, false, false).map(Some)
}

// ---------------------------------------------------------------------------
// Command line
// ---------------------------------------------------------------------------

#[derive(Subcommand)]
pub enum Command {
    /// List the agent environments the skill can go into, and where it is installed (JSON)
    List,
    /// Print the generated SKILL.md
    Show,
    /// Install the skill (default: every agent environment detected here)
    Install {
        /// Target ids, e.g. `claude-code codex`. Omit to use every detected agent.
        targets: Vec<String>,
        /// Every supported target, detected or not
        #[arg(long)]
        all: bool,
        /// Report what would change without writing anything
        #[arg(long)]
        dry_run: bool,
        /// Overwrite a SKILL.md that vibe99ctl did not generate
        #[arg(long)]
        force: bool,
    },
    /// Remove the skill
    Uninstall {
        /// Target ids. Omit to remove it from every target that has it.
        targets: Vec<String>,
        /// Every supported target
        #[arg(long)]
        all: bool,
        /// Report what would change without writing anything
        #[arg(long)]
        dry_run: bool,
    },
}

/// Entry point. Returns the process exit code; the caller exits with it.
pub fn run(command: &Command) -> i32 {
    match command {
        Command::Show => {
            print!("{}", render_skill());
            0
        }
        Command::List => match list() {
            Ok(report) => print_report(&report),
            Err(error) => fail(&error),
        },
        Command::Install {
            targets,
            all,
            dry_run,
            force,
        } => {
            let selection = match select(targets, *all, false) {
                Ok(selection) => selection,
                Err(error) => return fail(&error),
            };
            let home = match cli_registry::home_dir() {
                Ok(home) => home,
                Err(error) => return fail(&error),
            };
            match install_report(&selection, &home, *dry_run, *force) {
                Ok(report) => print_report(&report),
                Err(error) => fail(&error),
            }
        }
        Command::Uninstall {
            targets,
            all,
            dry_run,
        } => {
            let selection = match select(targets, *all, true) {
                Ok(selection) => selection,
                Err(error) => return fail(&error),
            };
            let home = match cli_registry::home_dir() {
                Ok(home) => home,
                Err(error) => return fail(&error),
            };
            match uninstall_report(&selection, &home, *dry_run) {
                Ok(report) => print_report(&report),
                Err(error) => fail(&error),
            }
        }
    }
}

/// Uninstall with no ids means "everywhere it is installed", not "everything":
/// removing a target that never had the skill is a no-op, but it keeps the
/// report honest.
fn select(
    ids: &[String],
    all: bool,
    installed_only: bool,
) -> Result<Vec<&'static SkillTarget>, String> {
    if all {
        if !ids.is_empty() {
            return Err("pass target ids or --all, not both".to_string());
        }
        return Ok(TARGETS.iter().collect());
    }
    if !ids.is_empty() {
        return ids.iter().map(|id| find(id)).collect();
    }

    let home = cli_registry::home_dir()?;
    let default_set: Vec<&'static SkillTarget> = TARGETS
        .iter()
        .filter(|target| {
            if installed_only {
                target
                    .files(&home)
                    .iter()
                    .any(|path| path.exists())
            } else {
                target.is_detected(&home)
            }
        })
        .collect();
    if default_set.is_empty() {
        return Err(format!(
            "no agent environment found; pass target ids or --all (supported: {})",
            TARGETS
                .iter()
                .map(|target| target.id)
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    Ok(default_set)
}

fn list() -> Result<Value, String> {
    let home = cli_registry::home_dir()?;
    let current = render_skill();
    Ok(json!({
        "skill": {
            "name": SKILL_NAME,
            "file": "SKILL.md",
            "bytes": current.len(),
            "version": env!("CARGO_PKG_VERSION"),
        },
        "home": home.display().to_string(),
        "targets": TARGETS
            .iter()
            .map(|target| json!({
                "id": target.id,
                "name": target.name,
                "detected": target.is_detected(&home),
                "dirs": target.display_dirs(),
                "files": target
                    .files(&home)
                    .into_iter()
                    .map(|path| {
                        let existing = fs::read_to_string(&path).ok();
                        json!({
                            "path": path.display().to_string(),
                            "installed": existing
                                .as_deref()
                                .map(|text| text.contains(GENERATED_MARKER))
                                .unwrap_or(false),
                            "current": existing.as_deref() == Some(current.as_str()),
                        })
                    })
                    .collect::<Vec<_>>(),
            }))
            .collect::<Vec<_>>(),
    }))
}

fn print_report(report: &Value) -> i32 {
    println!(
        "{}",
        serde_json::to_string_pretty(report).unwrap_or_default()
    );
    0
}

fn fail(error: &str) -> i32 {
    eprintln!("Error: {error}");
    1
}

