const TRIGGER_DESCRIPTION: &str = "Control a running Vibe99 terminal workspace from the shell — list, create, focus and close panes; send keys to a terminal; switch, save and open layouts; read and write settings; manage shell profiles; and show or hide the floating pane indicator. Use when the user asks you to open or arrange Vibe99 panes, type into one, inspect the workspace, or change how Vibe99 looks or behaves.";

const INTRO: &str = r#"# vibe99ctl — drive Vibe99 from a shell

Vibe99 is a desktop terminal workspace for agentic coding: one pane holds the
spotlight, the rest stack beside it with their last lines visible, and a pane
whose agent has gone quiet pulses with a breathing alert.

`vibe99ctl` is its command line. It speaks JSON-RPC 2.0 to the running app over
a local socket (a Unix domain socket, or a named pipe on Windows), and every
capability listed below is one call. Reach for it when the user asks you to
open, arrange or type into Vibe99 panes, switch layouts, change a setting, or
manage shell profiles.

If `vibe99ctl` is not on PATH, run `install-cli` from the copy that ships with
the app, or tell the user where Vibe99 is installed instead of guessing.

## Before you call anything

```bash
vibe99ctl describe                         # every method, as JSON — read this first
vibe99ctl describe --method pane.create    # one method: params, example, return
vibe99ctl describe | jq .transport         # socket path, pid, is Vibe99 running?
```

`describe` is static data and works with Vibe99 closed. Every other command
needs the app running: when it is not, the CLI exits non-zero with a clear
message rather than hanging.

## Rules

- **Never invent a method or a parameter.** `describe` is the contract. An
  unknown method is rejected with `-32601`; a missing or malformed parameter
  with `-32602`.
- **Read, then write.** `pane list` is the only source of live pane ids — they
  change between sessions. `settings schema` lists every writable setting with
  its type, range and default, and `settings set` validates against it, so an
  invalid value is rejected instead of corrupting the config.
- **`--window <label>` picks the window.** Default `main`; a layout window is
  labelled with its layout id. `--timeout <seconds>` (default 5) bounds how long
  the CLI waits for the UI to answer a call.
- **Success is JSON on stdout; failure exits non-zero** with a JSON-RPC error
  code on stderr. A *refusal by the UI* is still a successful call: its result
  carries `{"ok": false, "reason": "..."}` — read the reason, do not retry
  blindly.
- **Destructive calls are deliberate.** `pane.close` refuses to close the last
  pane; `pane.requestClose` shows the user the same confirmation the UI would,
  so the user stays in control.

## Typical workflows

### Open a pane and run a command

```bash
pane=$(vibe99ctl pane create | jq -r .)
vibe99ctl terminal send-keys "$pane" "npm test"$'\n'
```

`terminal.send-keys` writes text as if it had been typed; end it with a newline
to press Enter. `pane create --shell <profile-id>` starts the pane with a
specific shell or SSH profile.

### Find the agent that needs attention

```bash
vibe99ctl focus.nextLit    # focus the next pane with a pending alert
```

It fails with reason `no-lit` when every agent is quiet, so it is safe to poll.

### Save and switch layouts

```bash
vibe99ctl layout list
vibe99ctl layout save           # persist the current window as its layout
vibe99ctl layout activate work  # focus that layout's window, or open it
```

### Change how Vibe99 looks or behaves

```bash
vibe99ctl settings schema
vibe99ctl settings set fontSize 16
vibe99ctl settings set breathingIntensity intense
vibe99ctl settings set layoutHotkeys --json '{"work":"F1"}'
```

Settings apply immediately in every open window; only the WebGL renderer flag
waits for a restart.

### Show or hide the floating pane indicator

```bash
vibe99ctl float on
vibe99ctl float status   # {"open": true}
vibe99ctl float off
```

`float.set` is idempotent — retrying it cannot flip the window the wrong way —
and `float.status` reports the live state.

### Point a pane at a saved SSH profile

```bash
vibe99ctl shell list
vibe99ctl pane create --shell prod
```

`profile create --name prod --command ssh --args ...` creates one from scratch;
`profile create --open` also opens a pane on it in the same call.

"#;

/// Render `SKILL.md`. Pure: the same registry produces the same file, which is
/// what makes install idempotent and the drift test meaningful.
pub fn render_skill() -> String {
    let mut out = String::new();
    out.push_str("---\n");
    out.push_str(&format!("name: {SKILL_NAME}\n"));
    out.push_str(&format!("description: {TRIGGER_DESCRIPTION}\n"));
    out.push_str("---\n\n");
    out.push_str(&format!(
        "{GENERATED_MARKER} {} — refresh with `vibe99ctl skill install` -->\n\n",
        env!("CARGO_PKG_VERSION")
    ));
    out.push_str(INTRO);
    out.push_str("## Methods\n\n");
    out.push_str(
        "The same list as `describe`, in registry order. Parameters marked with a\n\
         trailing `?` are optional; `call` is the exact CLI invocation.\n\
         `vibe99ctl call <method> --params '<json>'` reaches every method, including\n\
         those without a shortcut.\n",
    );
    out.push_str(&render_methods());
    out.push_str(&render_errors());
    out.push_str(
        "## Keeping this file current\n\n\
         This skill is generated from Vibe99's method registry, so it covers every\n\
         method `describe` reports. After upgrading Vibe99, refresh it:\n\n\
         ```bash\n\
         vibe99ctl skill list     # what is installed, and where\n\
         vibe99ctl skill install  # reinstall for every detected agent\n\
         vibe99ctl skill show     # print this file\n\
         ```\n",
    );
    out
}

fn render_methods() -> String {
    let mut out = String::new();
    let mut group: Option<&str> = None;
    for spec in cli_registry::METHODS {
        let next = spec.name.split('.').next().unwrap_or(spec.name);
        if group != Some(next) {
            out.push_str(&format!("\n### {next}\n\n"));
            group = Some(next);
        }
        out.push_str(&render_method(spec));
    }
    out.push('\n');
    out
}

fn render_method(spec: &MethodSpec) -> String {
    let mut details: Vec<String> = Vec::new();
    if !spec.params.is_empty() {
        let params = spec
            .params
            .iter()
            .map(render_param)
            .collect::<Vec<_>>()
            .join(", ");
        details.push(format!("Params: {params}"));
    }
    details.push(format!("Call: `{}`", call_for(spec)));
    details.push(format!("Returns: {}", spec.returns));

    format!(
        "- **`{}`** — {}\n  {}\n",
        spec.name,
        spec.summary,
        details.join(" · ")
    )
}

fn render_param(param: &ParamSpec) -> String {
    let name = if param.required {
        format!("`{}`", param.name)
    } else {
        format!("`{}?`", param.name)
    };
    let ty = if param.enum_values.is_empty() {
        param.ty.to_string()
    } else {
        param
            .enum_values
            .iter()
            .map(|value| format!("\"{value}\""))
            .collect::<Vec<_>>()
            .join(" | ")
    };
    let ty = if param.nullable {
        format!("{ty} | null")
    } else {
        ty
    };
    format!("{name}: {ty}")
}

fn call_for(spec: &MethodSpec) -> String {
    match spec.cli {
        Some(cli) => cli.to_string(),
        None => format!(
            "vibe99ctl call {} --params '{}'",
            spec.name, spec.example_params
        ),
    }
}

fn render_errors() -> String {
    let mut out = String::from("\n## Error codes\n\n| Code | Name | Meaning |\n|---|---|---|\n");
    for error in cli_registry::ERROR_CODES {
        out.push_str(&format!(
            "| {} | `{}` | {} |\n",
            error.code, error.name, error.meaning
        ));
    }
    out
}

