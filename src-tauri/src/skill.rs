/// What install or uninstall does to one file.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FileAction {
    /// The file will be (or was) created.
    Create,
    /// The file exists and will be (or was) rewritten.
    Update,
    /// The file is already in the requested state.
    Unchanged,
    /// The file will be (or was) deleted.
    Remove,
    /// The file is not ours; left untouched.
    Refused,
}

impl FileAction {
    pub const fn slug(self) -> &'static str {
        match self {
            FileAction::Create => "create",
            FileAction::Update => "update",
            FileAction::Unchanged => "unchanged",
            FileAction::Remove => "remove",
            FileAction::Refused => "refused",
        }
    }

    fn writes(self) -> bool {
        matches!(self, FileAction::Create | FileAction::Update)
    }
}

pub struct FilePlan {
    pub path: PathBuf,
    pub action: FileAction,
    /// Why the file was refused, or anything else worth reporting.
    pub detail: Option<String>,
}

/// Compute what installing into `target` would do, without touching disk.
pub fn plan_install(target: &SkillTarget, home: &Path, force: bool) -> Vec<FilePlan> {
    let wanted = render_skill();
    target
        .files(home)
        .into_iter()
        .map(|path| match fs::read_to_string(&path) {
            Err(error) if error.kind() == io::ErrorKind::NotFound => FilePlan {
                path,
                action: FileAction::Create,
                detail: None,
            },
            Err(error) => FilePlan {
                path,
                action: FileAction::Refused,
                detail: Some(format!("cannot read the existing file: {error}")),
            },
            Ok(existing) if existing == wanted => FilePlan {
                path,
                action: FileAction::Unchanged,
                detail: None,
            },
            Ok(existing) if existing.contains(GENERATED_MARKER) || force => FilePlan {
                path,
                action: FileAction::Update,
                detail: None,
            },
            Ok(_) => FilePlan {
                path,
                action: FileAction::Refused,
                detail: Some(
                    "an existing SKILL.md was not generated by vibe99ctl; pass --force to overwrite it"
                        .to_string(),
                ),
            },
        })
        .collect()
}

/// Compute what uninstalling from `target` would do, without touching disk.
pub fn plan_uninstall(target: &SkillTarget, home: &Path) -> Vec<FilePlan> {
    target
        .files(home)
        .into_iter()
        .map(|path| match fs::read_to_string(&path) {
            Err(error) if error.kind() == io::ErrorKind::NotFound => FilePlan {
                path,
                action: FileAction::Unchanged,
                detail: Some("not installed".to_string()),
            },
            Err(error) => FilePlan {
                path,
                action: FileAction::Refused,
                detail: Some(format!("cannot read the existing file: {error}")),
            },
            Ok(existing) if existing.contains(GENERATED_MARKER) => FilePlan {
                path,
                action: FileAction::Remove,
                detail: None,
            },
            Ok(_) => FilePlan {
                path,
                action: FileAction::Refused,
                detail: Some(
                    "the existing SKILL.md was not generated by vibe99ctl; leaving it alone".to_string(),
                ),
            },
        })
        .collect()
}

/// Write the files an install plan asked for. Refused and unchanged plans are
/// reported but never written. `dry_run` writes nothing.
pub fn apply_install(plans: &[FilePlan], dry_run: bool) -> Result<(), String> {
    let contents = render_skill();
    for plan in plans.iter().filter(|plan| plan.action.writes()) {
        if dry_run {
            continue;
        }
        if let Some(parent) = plan.path.parent() {
            fs::create_dir_all(parent)
                .map_err(|error| format!("cannot create {}: {error}", parent.display()))?;
        }
        write_atomic(&plan.path, contents.as_bytes())?;
    }
    Ok(())
}

/// Delete the files an uninstall plan owns, and prune the now-empty skill
/// directory. `dry_run` deletes nothing.
pub fn apply_uninstall(plans: &[FilePlan], dry_run: bool) -> Result<(), String> {
    for plan in plans
        .iter()
        .filter(|plan| plan.action == FileAction::Remove)
    {
        if dry_run {
            continue;
        }
        fs::remove_file(&plan.path)
            .map_err(|error| format!("cannot remove {}: {error}", plan.path.display()))?;
        // Only removes the directory when it is empty, i.e. nothing else lives
        // in this skill folder.
        if let Some(dir) = plan.path.parent() {
            let _ = fs::remove_dir(dir);
        }
    }
    Ok(())
}

fn plan_json(plan: &FilePlan) -> Value {
    json!({
        "path": plan.path.display().to_string(),
        "action": plan.action.slug(),
        "detail": plan.detail,
    })
}

fn target_report(target: &SkillTarget, home: &Path, plans: &[FilePlan], dry_run: bool) -> Value {
    json!({
        "id": target.id,
        "name": target.name,
        "detected": target.is_detected(home),
        "files": plans.iter().map(plan_json).collect::<Vec<_>>(),
        "dryRun": dry_run,
    })
}

/// Install into every given target and return the JSON report.
pub fn install_report(
    targets: &[&'static SkillTarget],
    home: &Path,
    dry_run: bool,
    force: bool,
) -> Result<Value, String> {
    let mut entries = Vec::new();
    for target in targets {
        let plans = plan_install(target, home, force);
        apply_install(&plans, dry_run)?;
        entries.push(target_report(target, home, &plans, dry_run));
    }
    Ok(json!({
        "skill": SKILL_NAME,
        "home": home.display().to_string(),
        "dryRun": dry_run,
        "targets": entries,
    }))
}

/// Uninstall from every given target and return the JSON report.
pub fn uninstall_report(
    targets: &[&'static SkillTarget],
    home: &Path,
    dry_run: bool,
) -> Result<Value, String> {
    let mut entries = Vec::new();
    for target in targets {
        let plans = plan_uninstall(target, home);
        apply_uninstall(&plans, dry_run)?;
        entries.push(target_report(target, home, &plans, dry_run));
    }
    Ok(json!({
        "skill": SKILL_NAME,
        "home": home.display().to_string(),
        "dryRun": dry_run,
        "targets": entries,
    }))
}

/// One line per file worth mentioning, for the human-readable output of
/// `install-cli` and `enhance install`. Quiet about "unchanged" files only
/// when they were already current — a refused file is always called out.
pub fn summary_lines(report: &Value) -> Vec<String> {
    let mut lines = Vec::new();
    for target in report["targets"].as_array().into_iter().flatten() {
        let name = target["name"].as_str().unwrap_or("agent");
        for file in target["files"].as_array().into_iter().flatten() {
            let path = file["path"].as_str().unwrap_or("");
            let action = file["action"].as_str().unwrap_or("");
            match action {
                "create" | "update" => lines.push(format!("skill {action}d for {name}: {path}")),
                "remove" => lines.push(format!("skill removed for {name}: {path}")),
                "refused" => lines.push(format!(
                    "skill not installed for {name}: {}",
                    file["detail"].as_str().unwrap_or("refused")
                )),
                _ => lines.push(format!("skill already current for {name}: {path}")),
            }
        }
    }
    lines
}

